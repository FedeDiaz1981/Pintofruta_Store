"""Generate the embedded VBA project. Build-time tools only; production uses Node.

python -m pip install -r scripts/excel/requirements.txt
python scripts/build-remito-vba.py
python scripts/build-remito-vba.py --customer-order
"""

import argparse
import base64
from datetime import timedelta
import os
from pathlib import Path
import struct
import tempfile
import uuid

from ms_ovba.Models.Entities.doc_module import DocModule
from ms_ovba.Models.Entities.reference import Reference
from ms_ovba.Models.Entities.reference_registered import ReferenceRegistered
from ms_ovba.Models.Fields.libid_reference import LibidReference
from ms_ovba.Views.project_ole_file import ProjectOleFile
from ms_ovba.vbaProject import VbaProject
from ms_dtyp.filetime import Filetime
from ms_ovba_compression.ms_ovba import MsOvba
from oletools.olevba import VBA_Parser


root = Path(__file__).resolve().parents[1]
arguments = argparse.ArgumentParser()
arguments.add_argument("--customer-order", action="store_true")
customer_order = arguments.parse_args().customer_order
# Windows cannot turn the 1601 FILETIME epoch into a Unix timestamp.
Filetime.from_msfiletime = classmethod(
    lambda cls, value: cls(1601, 1, 1) + timedelta(microseconds=value // 10)
)


def literal_container(data):
    # MS-OVBA 2.4.1: literal tokens avoid the library's incorrect copy-token output.
    body = b"".join(b"\x00" + data[index:index + 8] for index in range(0, len(data), 8))
    if not body or len(body) > 4096:
        raise ValueError("The VBA source must fit in one literal chunk (3640 bytes).")
    return b"\x01" + struct.pack("<H", 0xB000 | (len(body) - 1)) + body


MsOvba.compress = lambda self, data: literal_container(data)
project = VbaProject()
project.project_id = "{6CB33563-DC49-4D60-B868-60A43F72282E}"
references = [
    ("VBA", "000204EF-0000-0000-C000-000000000046", "4.0", r"C:\Windows\System32\VBE6.DLL", "Visual Basic For Applications"),
    ("Excel", "00020813-0000-0000-C000-000000000046", "1.6", r"C:\Program Files\Microsoft Office\Office12\EXCEL.EXE", "Microsoft Excel 12.0 Object Library"),
    ("stdole", "00020430-0000-0000-C000-000000000046", "2.0", r"C:\Windows\System32\stdole2.tlb", "OLE Automation"),
]
for name, guid, version, location, title in references:
    reference = LibidReference(uuid.UUID(guid), version, "0", location, title)
    project.add_reference(Reference(ReferenceRegistered(reference), name))

workbook_source = "scripts/excel/CustomerOrderWorkbook.cls" if customer_order else "scripts/excel/ThisWorkbook.cls"
sources = {"ThisWorkbook": (root / workbook_source).read_text(encoding="ascii")}
for index in range(1, 3 if customer_order else 2):
    name = f"Sheet{index}"
    sources[name] = '\n'.join([
        f'Attribute VB_Name = "{name}"',
        'Attribute VB_Base = "0{00020820-0000-0000-C000-000000000046}"',
        'Attribute VB_GlobalNameSpace = False',
        'Attribute VB_Creatable = False',
        'Attribute VB_PredeclaredId = True',
        'Attribute VB_Exposed = True',
        'Attribute VB_TemplateDerived = False',
        'Attribute VB_Customizable = True',
        'Option Explicit',
        '',
    ])

with tempfile.TemporaryDirectory(prefix="pintofruta-vba-") as build_dir:
    previous_dir = Path.cwd()
    try:
        os.chdir(build_dir)
        for name, source in sources.items():
            module = DocModule(name)
            module.add_file(str(Path(build_dir) / name))
            Path(module.bin_path.removesuffix(".bin") + ".new").write_bytes(
                source.replace("\r\n", "\n").replace("\n", "\r\n").encode("ascii")
            )
            project.add_module(module)
        ProjectOleFile.write_file(project)
        binary = Path("vbaProject.bin").read_bytes()
    finally:
        os.chdir(previous_dir)

encoded = base64.b64encode(binary).decode("ascii")
parser = VBA_Parser("remito.bin", data=binary)
try:
    extracted = {name: code for _, _, name, code in parser.extract_macros()}
finally:
    parser.close()
for name, expected in sources.items():
    actual = extracted[f"{name}.cls"]
    if isinstance(actual, bytes):
        actual = actual.decode("ascii")
    assert actual.replace("\r\n", "\n").strip() == expected.replace("\r\n", "\n").strip()
output = root / ("src/lib/customer-order-vba-project.ts" if customer_order else "src/lib/remito-vba-project.ts")
constant = "CUSTOMER_ORDER_VBA_PROJECT_BASE64" if customer_order else "REMITO_VBA_PROJECT_BASE64"
output.write_text(
    f'// Generated by scripts/build-remito-vba.py from {workbook_source}.\n'
    f'export const {constant} = "{encoded}";\n',
    encoding="ascii",
)
print(f"Generated {output.name}: {len(binary)} bytes")
